            GpuVoltageMv = 1100,
            CpuPptW = 88,
            CpuTdcA = 60,
            CpuEdcA = 90,
            CpuMinFrequencyPercent = 20,
            CpuMaxFrequencyPercent = 100,
            CpuBoostMode = ProcessorBoostMode.Enabled,
            SafetyLimits = new SafetyLimits { MaxCpuTemperatureC = 90, MaxGpuTemperatureC = 85, MaxGpuHotspotTemperatureC = 100 }
        });

        _profiles.Add(new TuningProfile
        {
            Name = "Idle / saver",
            TargetWorkload = WorkloadClass.Idle,
            TargetWorkloadType = WorkloadType.Idle,
            PreferredPowerPlan = WindowsPowerPlanKind.PowerSaver,
            GpuPowerLimitPercent = 50,
